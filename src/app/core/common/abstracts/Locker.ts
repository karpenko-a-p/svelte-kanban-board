/**
 * Защита класса от приведения к другому схожему по составу полей и методов классу
 * @description защита класса от утиной типизации в ts, добавляет к классу уникальное поле, которое делает сам класс уникальным даже на уровне типов
 */
export abstract class Locker<T extends string> {
  /**
   * Защитное поле существующее только на уровне типизации
   */
  declare private readonly lock: T;
}
